USE olist_ecommerce;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 1: CANONICAL RFM CUSTOMER VIEW
-- Purpose: Score and segment customers by Recency, Frequency, and Monetary value
-- Source View: vw_customer_lifetime_summary
-- Grain: One row per customer_unique_id
--
-- Method note:
-- Recency and monetary scores use quintiles. Frequency uses observed order-count
-- thresholds because the dataset is dominated by one-time buyers, so NTILE would
-- split customers with the same frequency into different score groups.
-- This is the canonical RFM logic used by the Tableau customer dashboard.
-- -------------------------------------------------------------------------

CREATE OR REPLACE VIEW vw_rfm_customers AS

WITH rfm_scores AS (
    SELECT
        customer_unique_id,
        recency_days,
        total_orders AS frequency,
        total_spend AS monetary_value,

        NTILE(5) OVER (
            ORDER BY recency_days DESC
        ) AS r_score,

        CASE
            WHEN total_orders = 1 THEN 1
            WHEN total_orders = 2 THEN 2
            WHEN total_orders = 3 THEN 3
            WHEN total_orders BETWEEN 4 AND 5 THEN 4
            ELSE 5
        END AS f_score,

        NTILE(5) OVER (
            ORDER BY total_spend ASC
        ) AS m_score

    FROM vw_customer_lifetime_summary
),

rfm_segmented AS (
    SELECT
        customer_unique_id,
        recency_days,
        frequency,
        monetary_value,
        r_score,
        f_score,
        m_score,

        CASE
            WHEN r_score >= 4
                 AND f_score >= 4
                 AND m_score >= 4
                THEN 'Champions'

            WHEN r_score >= 3
                 AND f_score >= 2
                 AND m_score >= 3
                THEN 'Loyal Customers'

            WHEN r_score >= 4
                 AND f_score = 1
                 AND m_score >= 3
                THEN 'Potential Loyalists'

            WHEN r_score = 5
                 AND f_score = 1
                 AND m_score <= 2
                THEN 'Recent Customers'

            WHEN r_score <= 2
                 AND f_score >= 2
                THEN 'At Risk'

            WHEN r_score <= 2
                 AND f_score = 1
                THEN 'Hibernating'

            ELSE 'Others'
        END AS rfm_segment

    FROM rfm_scores
)

SELECT
    customer_unique_id,
    recency_days,
    frequency,
    monetary_value,
    r_score,
    f_score,
    m_score,
    rfm_segment
FROM rfm_segmented;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 2: RFM SEGMENT PROFILE
-- Purpose: Summarize the size and behavior of each RFM segment
-- Source View: vw_rfm_customers
-- Grain of Output: One row per RFM segment
-- -------------------------------------------------------------------------

SELECT
    rfm_segment,
    COUNT(*) AS customer_count,

    ROUND(
        COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (),
        2
    ) AS customer_share_pct,

    ROUND(AVG(recency_days), 1) AS avg_recency_days,
    ROUND(AVG(frequency), 2) AS avg_orders_per_customer,
    ROUND(AVG(monetary_value), 2) AS avg_customer_spend

FROM vw_rfm_customers

GROUP BY rfm_segment

ORDER BY customer_count DESC;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 3: CUSTOMER SPEND CONCENTRATION
-- Purpose: Measure how much cumulative spend is generated by the top
--          1%, 5%, 10%, and 20% of customers
-- Source View: vw_customer_lifetime_summary
-- Grain of Output: One row per customer concentration threshold
-- -------------------------------------------------------------------------

WITH ranked_customers AS (
    SELECT
        customer_unique_id,
        total_spend,

        ROW_NUMBER() OVER (
            ORDER BY total_spend DESC, customer_unique_id
        ) AS customer_rank,

        COUNT(*) OVER () AS total_customers,

        SUM(total_spend) OVER () AS overall_spend,

        SUM(total_spend) OVER (
            ORDER BY total_spend DESC, customer_unique_id
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ) AS cumulative_spend

    FROM vw_customer_lifetime_summary
),

customer_concentration AS (
    SELECT
        customer_rank,
        customer_rank * 100.0 / total_customers AS cumulative_customer_pct,
        cumulative_spend * 100.0 / overall_spend AS cumulative_spend_pct
    FROM ranked_customers
),

concentration_bands AS (
    SELECT
        CASE
            WHEN cumulative_customer_pct <= 1 THEN 'Top 1%'
            WHEN cumulative_customer_pct <= 5 THEN 'Top 5%'
            WHEN cumulative_customer_pct <= 10 THEN 'Top 10%'
            WHEN cumulative_customer_pct <= 20 THEN 'Top 20%'
        END AS customer_group,
        cumulative_customer_pct,
        cumulative_spend_pct
    FROM customer_concentration
    WHERE cumulative_customer_pct <= 20
)

SELECT
    customer_group,
    ROUND(MAX(cumulative_spend_pct), 2) AS cumulative_spend_share_pct

FROM concentration_bands

GROUP BY customer_group

ORDER BY
    CASE customer_group
        WHEN 'Top 1%' THEN 1
        WHEN 'Top 5%' THEN 2
        WHEN 'Top 10%' THEN 3
        WHEN 'Top 20%' THEN 4
    END;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 4: CATEGORY RANKING BY YEAR
-- Purpose: Rank product categories by delivered product value within each year
-- Source View: vw_order_item_details
-- Grain of Output: One row per year + product category
-- Analysis Period: January 2017 through August 2018
-- -------------------------------------------------------------------------

WITH category_yearly_sales AS (
    SELECT
        YEAR(order_purchase_timestamp) AS order_year,

        product_category_name_english AS product_category,

        COUNT(DISTINCT order_id) AS delivered_orders,
        COUNT(*) AS items_sold,
        ROUND(SUM(price), 2) AS product_value

    FROM vw_order_item_details

    WHERE order_status = 'delivered'
      AND order_purchase_timestamp >= '2017-01-01'
      AND order_purchase_timestamp < '2018-09-01'

    GROUP BY
        YEAR(order_purchase_timestamp),
        product_category_name_english
),

ranked_categories AS (
    SELECT
        order_year,
        product_category,
        delivered_orders,
        items_sold,
        product_value,

        DENSE_RANK() OVER (
            PARTITION BY order_year
            ORDER BY product_value DESC
        ) AS category_rank

    FROM category_yearly_sales
)

SELECT
    order_year,
    category_rank,
    product_category,
    delivered_orders,
    items_sold,
    product_value

FROM ranked_categories

WHERE category_rank <= 10

ORDER BY
    order_year,
    category_rank;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 5: SELLER RANKING WITHIN STATE
-- Purpose: Rank sellers by delivered product value within each seller state
-- Source View: vw_order_item_details
-- Grain of Output: One row per seller
-- -------------------------------------------------------------------------

WITH seller_sales AS (
    SELECT
        seller_id,
        seller_city,
        seller_state,
        COUNT(DISTINCT order_id) AS delivered_orders,
        COUNT(*) AS items_sold,
        ROUND(SUM(price), 2) AS product_value

    FROM vw_order_item_details

    WHERE order_status = 'delivered'

    GROUP BY
        seller_id,
        seller_city,
        seller_state
),

ranked_sellers AS (
    SELECT
        seller_id,
        seller_city,
        seller_state,
        delivered_orders,
        items_sold,
        product_value,

        DENSE_RANK() OVER (
            PARTITION BY seller_state
            ORDER BY product_value DESC
        ) AS seller_rank_in_state

    FROM seller_sales
)

SELECT
    seller_state,
    seller_rank_in_state,
    seller_id,
    seller_city,
    delivered_orders,
    items_sold,
    product_value

FROM ranked_sellers

WHERE seller_rank_in_state <= 5

ORDER BY
    seller_state,
    seller_rank_in_state;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 6: RUNNING MONTHLY PAYMENT TOTAL
-- Purpose: Track cumulative delivered payment value over time
-- Source View: vw_order_financials
-- Grain of Output: One row per month
-- Analysis Period: January 2017 through August 2018
-- -------------------------------------------------------------------------

WITH monthly_payments AS (
    SELECT
        DATE_FORMAT(order_purchase_timestamp, '%Y-%m') AS order_month,
        ROUND(SUM(payment_total), 2) AS monthly_payment_value

    FROM vw_order_financials

    WHERE order_status = 'delivered'
      AND order_purchase_timestamp >= '2017-01-01'
      AND order_purchase_timestamp < '2018-09-01'

    GROUP BY DATE_FORMAT(order_purchase_timestamp, '%Y-%m')
)

SELECT
    order_month,
    monthly_payment_value,

    ROUND(
        SUM(monthly_payment_value) OVER (
            ORDER BY order_month
            ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
        ),
        2
    ) AS cumulative_payment_value

FROM monthly_payments

ORDER BY order_month;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 7: EXTREME LATE-DELIVERY OUTLIERS
-- Purpose: Identify the most severely delayed delivered orders
-- Source View: vw_order_delivery_performance
-- Grain of Output: One row per delayed order
-- -------------------------------------------------------------------------

WITH late_orders AS (
    SELECT
        order_id,
        customer_id,
        order_purchase_timestamp,
        order_delivered_customer_date,
        order_estimated_delivery_date,
        delivery_days,
        delivery_variance_days,

        ROW_NUMBER() OVER (
            ORDER BY delivery_variance_days DESC
        ) AS delay_rank

    FROM vw_order_delivery_performance

    WHERE order_status = 'delivered'
      AND delivery_status = 'Late'
      AND order_delivered_customer_date IS NOT NULL
)

SELECT
    delay_rank,
    order_id,
    customer_id,
    order_purchase_timestamp,
    order_estimated_delivery_date,
    order_delivered_customer_date,
    delivery_days,
    delivery_variance_days

FROM late_orders

WHERE delay_rank <= 20

ORDER BY delay_rank;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 8: POLISHED MONTH-OVER-MONTH GROWTH
-- Purpose: Measure monthly changes in delivered orders and payment value
-- Source View: vw_order_financials
-- Grain of Output: One row per month
-- Analysis Period: January 2017 through August 2018
-- -------------------------------------------------------------------------

WITH monthly_sales AS (
    SELECT
        DATE_FORMAT(order_purchase_timestamp, '%Y-%m') AS order_month,
        COUNT(*) AS delivered_orders,
        ROUND(SUM(payment_total), 2) AS payment_value

    FROM vw_order_financials

    WHERE order_status = 'delivered'
      AND order_purchase_timestamp >= '2017-01-01'
      AND order_purchase_timestamp < '2018-09-01'

    GROUP BY DATE_FORMAT(order_purchase_timestamp, '%Y-%m')
),

monthly_comparison AS (
    SELECT
        order_month,
        delivered_orders,
        payment_value,

        LAG(delivered_orders) OVER (
            ORDER BY order_month
        ) AS previous_month_orders,

        LAG(payment_value) OVER (
            ORDER BY order_month
        ) AS previous_month_payment_value

    FROM monthly_sales
)

SELECT
    order_month,
    delivered_orders,
    previous_month_orders,

    ROUND(
        (delivered_orders - previous_month_orders)
        * 100.0
        / NULLIF(previous_month_orders, 0),
        2
    ) AS order_growth_pct,

    payment_value,
    previous_month_payment_value,

    ROUND(
        (payment_value - previous_month_payment_value)
        * 100.0
        / NULLIF(previous_month_payment_value, 0),
        2
    ) AS payment_growth_pct

FROM monthly_comparison

ORDER BY order_month;


-- -------------------------------------------------------------------------
-- ADVANCED SQL ANALYSIS 9: CUSTOMER COHORT RETENTION
-- Purpose: Measure repeat purchasing behavior by customer acquisition month
-- Source Tables: orders + customers
-- Grain of Output: One row per cohort_month + months_since_cohort
-- Cohorts displayed: January 2017 through August 2018
--
-- Note:
-- Full delivered-order history before 2018-09-01 is used to identify each
-- customer's true first purchase. A recursive month grid fills valid inactive
-- months with zero while excluding months that had not yet elapsed.
-- -------------------------------------------------------------------------

WITH RECURSIVE month_numbers AS (
    SELECT 0 AS months_since_cohort

    UNION ALL

    SELECT months_since_cohort + 1
    FROM month_numbers
    WHERE months_since_cohort < 19
),

customer_orders AS (
    SELECT
        c.customer_unique_id,
        CAST(
            DATE_FORMAT(o.order_purchase_timestamp, '%Y-%m-01') AS DATE
        ) AS order_month
    FROM orders AS o
    INNER JOIN customers AS c
        ON o.customer_id = c.customer_id
    WHERE o.order_status = 'delivered'
      AND o.order_purchase_timestamp < '2018-09-01'
),

customer_cohorts AS (
    SELECT
        customer_unique_id,
        MIN(order_month) AS cohort_month
    FROM customer_orders
    GROUP BY customer_unique_id
),

cohort_activity AS (
    SELECT
        co.customer_unique_id,
        co.order_month,
        cc.cohort_month,
        TIMESTAMPDIFF(
            MONTH,
            cc.cohort_month,
            co.order_month
        ) AS months_since_cohort
    FROM customer_orders AS co
    INNER JOIN customer_cohorts AS cc
        ON co.customer_unique_id = cc.customer_unique_id
    WHERE cc.cohort_month >= '2017-01-01'
),

cohort_counts AS (
    SELECT
        cohort_month,
        months_since_cohort,
        COUNT(DISTINCT customer_unique_id) AS active_customers
    FROM cohort_activity
    GROUP BY
        cohort_month,
        months_since_cohort
),

cohort_sizes AS (
    SELECT
        cohort_month,
        COUNT(DISTINCT customer_unique_id) AS cohort_size
    FROM cohort_activity
    WHERE months_since_cohort = 0
    GROUP BY cohort_month
),

cohort_grid AS (
    SELECT
        cs.cohort_month,
        mn.months_since_cohort,
        cs.cohort_size
    FROM cohort_sizes AS cs
    CROSS JOIN month_numbers AS mn
    WHERE mn.months_since_cohort <= TIMESTAMPDIFF(
        MONTH,
        cs.cohort_month,
        '2018-08-01'
    )
)

SELECT
    cg.cohort_month,
    cg.months_since_cohort,
    COALESCE(cc.active_customers, 0) AS active_customers,
    cg.cohort_size,

    ROUND(
        COALESCE(cc.active_customers, 0) * 100.0 / cg.cohort_size,
        2
    ) AS retention_rate_pct

FROM cohort_grid AS cg

LEFT JOIN cohort_counts AS cc
    ON cg.cohort_month = cc.cohort_month
   AND cg.months_since_cohort = cc.months_since_cohort

ORDER BY
    cg.cohort_month,
    cg.months_since_cohort;
